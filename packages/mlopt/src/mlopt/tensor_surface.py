"""The vendored ``tensor.*`` surface artifact — ``host_surface.json``.

Pinned copy of the canonical surface generated by
``handl-lang/lib-tensor-native`` (``tools/dump_host_surface.py`` →
repo-root ``host_surface.json``: the handwritten ``op`` decls in
``src/index.hnl`` plus ``tool-codegen-aten --emit-spec`` for the
ATen-ported ops).  ``mlopt.emit``'s drift guards pin ``_OPS`` against
it; bump deliberately — never hand-edit the JSON.  Refresh by
copying the artifact from an lib-tensor-native checkout
(``scripts/sync_host_surface.py``).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

__all__ = ["host_ops", "surface_json_path"]

_SURFACE_JSON = Path(__file__).with_name("host_surface.json")


def surface_json_path() -> Path:
    """Return the vendored artifact path."""
    return _SURFACE_JSON


def host_ops() -> dict[str, dict[str, Any]]:
    """``tensor.<name>`` → surface entry, from the vendored artifact."""
    data = json.loads(_SURFACE_JSON.read_text())
    return {
        op["op"]: op for op in data["ops"] if isinstance(op, dict) and isinstance(op.get("op"), str)
    }
